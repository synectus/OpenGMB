import { actions } from "./actions";
import { PRIVATE_ACTIONS } from "./actions/private";
import { toolNameFor, type AnyAction } from "./registry";

/** Content of apps/web/app/_generated/actions.ts for the given registry. Pure, so tests can diff it. */
export function renderWebActions(list: readonly AnyAction[] = actions): string {
  const fns = list
    .map(
      (a) =>
        `/** ${a.description.replaceAll("*/", "* /")} */\n` +
        `export async function ${toolNameFor(a.name)}(input: unknown = {}) {\n` +
        `  return runAction(${JSON.stringify(a.name)}, input);\n` +
        `}\n`,
    )
    .join("\n");
  return (
    `"use server";\n` +
    `// GENERATED by \`pnpm gen:actions\` from the action registry in packages/core. DO NOT EDIT.\n` +
    `// Each function delegates to runAction (apps/web/lib/run-action.ts), which authenticates and\n` +
    `// calls executeAction. Add or change actions in packages/core, then re-run the generator.\n` +
    `import { runAction } from "../../lib/run-action";\n\n` +
    fns
  );
}

/** The actions of the community edition: the registry without the ones in actions/private.ts. */
export const communityActions = (list: readonly AnyAction[] = actions): readonly AnyAction[] =>
  list.filter((a) => !PRIVATE_ACTIONS.includes(a));
